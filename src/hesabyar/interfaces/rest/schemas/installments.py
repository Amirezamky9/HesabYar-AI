class EarlySettlementRequest(BaseModel):
    """Settle a plan early — full close or a partial payment.

    A settlement IS a receipt, so THE LINKAGE GUARD applies:
    ``invoice_id`` AND ``journal_move_id`` are both required. A
    ``full`` settlement must pay at least the payoff quote and
    closes every open leg; a ``partial`` settlement pays part of
    the schedule and re-amortises the rest.
    """

    model_config = ConfigDict(extra="forbid")

    invoice_id: str = Field(description="Original invoice ref (must equal the plan's invoice)")
    journal_move_id: int = Field(description="Engine move id of the accounting document")
    amount_toman: int = Field(description="Settlement amount in Toman (converted x10 to Rial)")
    settlement_type: str = Field(
        default="full", description="full | partial"
    )
    settlement_date: str | None = Field(
        default=None, description="Settlement date, Jalali YYYY-MM-DD (default: today)"
    )
    payment_method: str = Field(
        default="cash", description="cash | bank_transfer | other"
    )
    reference: str | None = Field(default=None, description="Caller-supplied settlement reference")
    notes: str | None = Field(default=None, description="Free-text notes")

    def payload_fields(self) -> dict[str, object]:
        """The domain validation payload (None values dropped)."""
        payload: dict[str, object] = {
            "invoice_id": self.invoice_id,
            "journal_move_id": self.journal_move_id,
            "amount_toman": self.amount_toman,
            "settlement_type": self.settlement_type,
            "payment_method": self.payment_method,
        }
        if self.settlement_date is not None:
            payload["settlement_date"] = self.settlement_date
        if self.reference is not None:
            payload["reference"] = self.reference
        if self.notes is not None:
            payload["notes"] = self.notes
        return payload


