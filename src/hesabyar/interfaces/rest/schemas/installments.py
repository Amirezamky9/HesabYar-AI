"""Request/response schemas for the installment endpoints (US-540 + US-541 + US-542 + US-543).

Responses map from the domain objects — no ORM object ever leaks.
The create bodies carry JSON types only; the domain validation
(``hesabyar.domain.installments.validation``) owns every rule, so
the service and the REST layer can never disagree about what is
valid. Dates travel as Jalali ``YYYY-MM-DD`` strings and are stored
as Gregorian dates. Amounts in requests are Toman
(``*_toman`` — converted ×10 to Rial at the boundary, once);
amounts in responses are Rial (``*_irr``) with ``*_toman``
alongside for display.

US-541 adds the finance endpoints: the payoff quote, the early
settlement (full + partial), the overdue report, and the dunning
run — plus the finance fields on contracts, receipts and plans.

US-543 (BNPL): plans carry ``kind`` (``internal`` | ``bnpl``) +
``gateway_channel_key``; BNPL receipts carry ``gateway`` +
``gateway_reference`` and link to their gateway payment; the plan
detail carries the gateway-side totals (receivable vs settled).
"""

