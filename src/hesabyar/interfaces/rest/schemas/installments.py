class ReceiptResponse(BaseModel):
    """One receipt with its allocations + advance.

    US-541: a settlement receipt also carries its finance-income
    and late-fee portions, the held advance it applied, and the
    ``is_early_settlement`` flag — so ``amount + applied_advance ==
    allocated + finance_income + late_fee + advance`` holds for
    every receipt.
    """

    id: str
    plan_id: str
    invoice_id: str
    journal_move_id: int
    amount_irr: int
    amount_toman: int
    received_date: str
    payment_method: str
    cheque_id: str | None
    collected_at: str | None
    allocations: list[LegAllocationResponse]
    allocated_irr: int
    advance_irr: int
    advance_toman: int
    finance_income_irr: int
    finance_income_toman: int
    late_fee_irr: int
    late_fee_toman: int
    applied_advance_irr: int
    applied_advance_toman: int
    is_early_settlement: bool
    reference: str | None
    notes: str | None
    #: US-543 (BNPL): the gateway link — None for non-BNPL receipts.
    #: ``gateway`` is the request-payload name (kept: the dashboard
    #: reads it); ``gateway_channel_key`` is the plan-response name
    #: (kept in sync — both carry the same value).
    gateway: str | None
    gateway_channel_key: str | None
    gateway_reference: str | None
    gateway_payment_id: str | None
    bnpl_status: str | None
    created_at: datetime

    @classmethod
    def from_receipt(cls, receipt: InstallmentReceipt) -> ReceiptResponse:
        return cls(
            id=receipt.id,
            plan_id=receipt.plan_id,
            invoice_id=receipt.invoice_id,
            journal_move_id=receipt.journal_move_id,
            amount_irr=receipt.amount.amount,
            amount_toman=receipt.amount.amount // 10,
            received_date=to_jalali_string(receipt.received_date.gregorian_date),
            payment_method=receipt.payment_method.value,
            cheque_id=receipt.cheque_id,
            collected_at=(
                to_jalali_string(receipt.collected_at.gregorian_date)
                if receipt.collected_at is not None
                else None
            ),
            allocations=[
                LegAllocationResponse.from_allocation(a) for a in receipt.allocations
            ],
            allocated_irr=receipt.allocated_irr,
            advance_irr=receipt.advance.amount,
            advance_toman=receipt.advance.amount // 10,
            finance_income_irr=receipt.finance_income.amount,
            finance_income_toman=receipt.finance_income.amount // 10,
            late_fee_irr=receipt.late_fee.amount,
            late_fee_toman=receipt.late_fee.amount // 10,
            applied_advance_irr=receipt.applied_advance.amount,
            applied_advance_toman=receipt.applied_advance.amount // 10,
            is_early_settlement=receipt.is_early_settlement,
            reference=receipt.reference,
            notes=receipt.notes,
            gateway=receipt.gateway_channel_key,
            gateway_channel_key=receipt.gateway_channel_key,
            gateway_reference=receipt.gateway_reference,
            gateway_payment_id=receipt.gateway_payment_id,
            bnpl_status=(
                receipt.bnpl_status.value if receipt.bnpl_status is not None else None
            ),
            created_at=receipt.created_at,
        )


