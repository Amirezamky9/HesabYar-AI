class CreatePlanRequest(BaseModel):
    """Create an installment plan: exactly one invoice, one schedule.

    Either the multi-stage payment terms (``total_principal_toman``
    + ``leg_count`` + ``interval_days`` + ``first_due_date`` — the
    legs are generated by equal split, remainder on the last leg)
    or explicit ``legs`` — never both. ``company_id`` is the
    HesabYar ``engine_companies`` row id or the engine's company id
    (both accepted, tenant-scoped).

    US-543 (BNPL): ``kind`` is ``internal`` (default — the customer
    pays the seller) or ``bnpl`` (the gateway pays the legs in
    tranches). A BNPL plan REQUIRES ``gateway_channel_key`` (the
    sale goes through exactly one gateway) and forbids
    ``contract_id``; an internal plan forbids ``gateway_channel_key``.
    """

    model_config = ConfigDict(extra="forbid")

    company_id: str = Field(description="HesabYar company row id or engine company id")
    invoice_id: str = Field(description="The ONE sales invoice this plan belongs to")
    contract_id: str | None = Field(
        default=None, description="Sale contract id (must exist in this installation)"
    )
    contract_code: str | None = Field(
        default=None,
        description="Sale contract code (US-541): the version in force is selected; "
        "either contract_id or contract_code, never both",
    )
    customer_ref: str | None = Field(default=None, description="Site customer reference")
    total_principal_toman: int | None = Field(
        default=None, description="Total principal in Toman (terms-based plans only)"
    )
    leg_count: int | None = Field(default=None, description="Number of legs (terms-based only)")
    interval_days: int | None = Field(
        default=None, description="Days between legs (terms-based only)"
    )
    first_due_date: str | None = Field(
        default=None, description="First leg due date, Jalali YYYY-MM-DD (terms-based only)"
    )
    legs: list[ExplicitLegRequest] | None = Field(
        default=None, description="Explicit legs (alternative to the payment terms)"
    )
    auto_post: bool = Field(
        default=False,
        description="Posting preference for journals later stories create (late fee, "
        "finance income): draft by default, auto-post only with an explicit "
        "opt-in (ADR 0003 decision 1)",
    )
    kind: str = Field(
        default="internal",
        description="Plan kind (US-543): internal | bnpl",
    )
    gateway_channel_key: str | None = Field(
        default=None,
        description="BNPL gateway channel key (US-543; required for BNPL plans, e.g. 'snapppay')",
    )

    def payload_fields(self) -> dict[str, object]:
        """The domain validation payload (None values dropped)."""
        payload: dict[str, object] = {
            "invoice_id": self.invoice_id,
            "auto_post": self.auto_post,
            "kind": self.kind,
        }
        if self.contract_id is not None:
            payload["contract_id"] = self.contract_id
        if self.contract_code is not None:
            payload["contract_code"] = self.contract_code
        if self.customer_ref is not None:
            payload["customer_ref"] = self.customer_ref
        if self.total_principal_toman is not None:
            payload["total_principal_toman"] = self.total_principal_toman
        if self.leg_count is not None:
            payload["leg_count"] = self.leg_count
        if self.interval_days is not None:
            payload["interval_days"] = self.interval_days
        if self.first_due_date is not None:
            payload["first_due_date"] = self.first_due_date
        if self.legs is not None:
            payload["legs"] = [
                {"due_date": leg.due_date, "principal_toman": leg.principal_toman}
                for leg in self.legs
            ]
        if self.gateway_channel_key is not None:
            payload["gateway_channel_key"] = self.gateway_channel_key
        return payload


class CreateReceiptRequest(BaseModel):
    """Record a receipt against a plan — THE LINKAGE GUARD applies.

    ``invoice_id`` AND ``journal_move_id`` are both required: a
    receipt without both refs is rejected with a typed 422
    (``INSTALLMENT_RECEIPT_LINKAGE_REQUIRED``). The invoice must be
    the plan's invoice. ``payment_method`` is ``cash`` /
    ``bank_transfer`` / ``other`` / ``cheque`` (US-542) or ``bnpl``
    (US-543 — BNPL plans only, with ``gateway`` +
    ``gateway_reference``). A cheque receipt MUST name its cheque
    (``cheque_id`` — a received commercial cheque in ``held`` or
    ``in_clearing``); its ``journal_move_id`` is the cheque's
    سند ۱ (the held journal). The leg it pays enters
    ``pending_clearance`` until the cheque clears.
    """

    model_config = ConfigDict(extra="forbid")

    invoice_id: str = Field(description="Original invoice ref (must equal the plan's invoice)")
    journal_move_id: int = Field(description="Engine move id of the accounting document")
    amount_toman: int = Field(description="Receipt amount in Toman (converted x10 to Rial)")
    received_date: str | None = Field(
        default=None, description="Receipt date, Jalali YYYY-MM-DD (default: today)"
    )
    payment_method: str = Field(
        default="cash", description="cash | bank_transfer | other | cheque | bnpl"
    )
    cheque_id: str | None = Field(
        default=None,
        description="Cheque id backing the receipt (required when payment_method is 'cheque', forbidden otherwise)",
    )
    reference: str | None = Field(default=None, description="Caller-supplied receipt reference")
    notes: str | None = Field(default=None, description="Free-text notes")
    gateway: str | None = Field(
        default=None,
        description="BNPL gateway channel key (US-543; required for BNPL receipts, e.g. 'snapppay')",
    )
    gateway_reference: str | None = Field(
        default=None,
        description="Gateway transaction id (US-543; required for BNPL receipts)",
    )

    def payload_fields(self) -> dict[str, object]:
        """The domain validation payload (None values dropped)."""
        payload: dict[str, object] = {
            "invoice_id": self.invoice_id,
            "journal_move_id": self.journal_move_id,
            "amount_toman": self.amount_toman,
            "payment_method": self.payment_method,
        }
        if self.received_date is not None:
            payload["received_date"] = self.received_date
        if self.cheque_id is not None:
            payload["cheque_id"] = self.cheque_id
        if self.reference is not None:
            payload["reference"] = self.reference
        if self.notes is not None:
            payload["notes"] = self.notes
        if self.gateway is not None:
            payload["gateway"] = self.gateway
        if self.gateway_reference is not None:
            payload["gateway_reference"] = self.gateway_reference
        return payload


class RejectBnplRequest(BaseModel):
    """Record a gateway rejection/cancellation for a BNPL receipt (US-543).

    Cancels the receipt's gateway payment, marks the receipt dead
    (its legs return to ``expected``), and files a review-queue
    item. ``reason`` is the gateway's reason (or the operator's),
    recorded on the review item.
    """

    model_config = ConfigDict(extra="forbid")

    reason: str = Field(description="Why the gateway rejected/cancelled the payment")


class CreateContractRequest(BaseModel):
    """Create one version of an installment sale contract.

    The late-fee rule is user-entered: ``late_fee_basis`` +
    ``late_fee_rate`` (+ ``late_fee_grace_days``). ``late_fee_rate``
    is a decimal string or integer — never a float. A rate is
    required unless the basis is ``none``.

    US-541 adds the finance terms: ``finance_income_rate`` (the
    fraction of principal charged as finance income over the whole
    plan), ``dunning_offsets`` (the stepped reminder schedule),
    ``receivable_account_engine_id`` (the debit side of the
    late-fee journal), and ``early_settlement_discount_rate``
    (required between 0 and 1 when the income policy is
    ``discounted``).
    """

    model_config = ConfigDict(extra="forbid")

    company_id: str = Field(description="HesabYar company row id or engine company id")
    code: str = Field(description="Contract code (versions share a code)")
    name: str = Field(description="Contract display name")
    version: int = Field(default=1, description="Contract version (increments per code)")
    effective_from: str = Field(description="Date this version takes effect, Jalali YYYY-MM-DD")
    late_fee_basis: str = Field(
        default="none",
        description="none | daily_percent | monthly_percent | fixed_per_day",
    )
    late_fee_rate: str | int = Field(
        default="0",
        description="Late-fee rate as a decimal string or integer (fraction for *_PERCENT, Rial/day for FIXED_PER_DAY)",
    )
    late_fee_grace_days: int = Field(
        default=0, description="Days past the due date before the late fee starts accruing"
    )
    penalty_account_engine_id: int | None = Field(
        default=None, description="Engine account id of the penalty (finance income) account"
    )
    penalty_account_code: str | None = Field(
        default=None, description="Chart code of the penalty account"
    )
    finance_income_rate: str | int = Field(
        default="0",
        description="Finance-income rate as a decimal string or integer (fraction of principal, e.g. 0.10 = 10%)",
    )
    dunning_offsets: list[int] | None = Field(
        default=None,
        description="Dunning reminder offsets in days past the due date, strictly increasing (e.g. [3, 7, 14, 30])",
    )
    receivable_account_engine_id: int | None = Field(
        default=None,
        description="Engine account id of the customer-receivable account "
        "(debit side of the late-fee journal)",
    )
    receivable_account_code: str | None = Field(
        default=None, description="Chart code of the receivable account"
    )
    early_settlement_fee_policy: str = Field(
        default="waived", description="Accrued late fees on early settlement: waived | kept"
    )
    early_settlement_income_policy: str = Field(
        default="waived",
        description="Unrealised finance income on early settlement: waived | discounted | full",
    )
    early_settlement_discount_rate: str | int = Field(
        default="0",
        description="Discount fraction on the remaining unrealised income when the income policy is 'discounted'",
    )
    supersedes_contract_id: str | None = Field(
        default=None, description="Previous version this version replaces"
    )

    def payload_fields(self) -> dict[str, object]:
        """The domain validation payload (None values dropped)."""
        payload: dict[str, object] = {
            "code": self.code,
            "name": self.name,
            "version": self.version,
            "effective_from": self.effective_from,
            "late_fee_basis": self.late_fee_basis,
            "late_fee_rate": self.late_fee_rate,
            "late_fee_grace_days": self.late_fee_grace_days,
            "finance_income_rate": self.finance_income_rate,
            "early_settlement_fee_policy": self.early_settlement_fee_policy,
            "early_settlement_income_policy": self.early_settlement_income_policy,
            "early_settlement_discount_rate": self.early_settlement_discount_rate,
        }
        if self.penalty_account_engine_id is not None:
            payload["penalty_account_engine_id"] = self.penalty_account_engine_id
        if self.penalty_account_code is not None:
            payload["penalty_account_code"] = self.penalty_account_code
        if self.dunning_offsets is not None:
            payload["dunning_offsets"] = self.dunning_offsets
        if self.receivable_account_engine_id is not None:
            payload["receivable_account_engine_id"] = self.receivable_account_engine_id
        if self.receivable_account_code is not None:
            payload["receivable_account_code"] = self.receivable_account_code
        if self.supersedes_contract_id is not None:
            payload["supersedes_contract_id"] = self.supersedes_contract_id
        return payload


