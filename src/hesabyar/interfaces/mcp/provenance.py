"""Shared §13.7 provenance for MCP financial results.

Every financial result an MCP tool returns MUST carry this provenance
block, built by :func:`build_provenance`. The shape is fixed by spec
§13.7; US-602/US-603/US-604 all import this module so the field names
never drift between tools.

Amounts themselves are NOT part of provenance: tools return integer Rial
values or safe decimal strings — never binary floating-point.
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import UTC, datetime

# Spec §13.7: a clear statement that the model interprets supplied data
# and does not create authoritative financial facts.
MODEL_INTERPRETATION_NOTICE = (
    "This report was generated by HesabYar from the Tryton accounting "
    "engine and HesabYar application services. An AI model reading this "
    "result interprets the supplied data; it does not create authoritative "
    "financial facts. Verify figures against the HesabYar dashboard or REST "
    "API before acting on them."
)


@dataclass(frozen=True)
class Provenance:
    """Spec §13.7 provenance block for one financial result."""

    company_id: int
    company_name: str | None
    period_label: str
    period_from: str | None = None
    period_to: str | None = None
    currency: str = "IRR"
    canonical_unit: str = "Rial"
    source_engine: str = "Tryton"
    report_type: str = ""
    generated_at: str = ""
    source_data_freshness: str = "live"
    snapshot_ref: str | None = None
    source_ref: str | None = None
    calculation_version: str = "1.0"
    ruleset_version: str | None = None
    validation_warnings: tuple[str, ...] = ()
    incomplete_data_warnings: tuple[str, ...] = ()
    notice: str = MODEL_INTERPRETATION_NOTICE

    def to_dict(self) -> dict[str, object]:
        return {
            "company_id": self.company_id,
            "company_name": self.company_name,
            "period": {
                "label": self.period_label,
                "from": self.period_from,
                "to": self.period_to,
            },
            "currency": self.currency,
            "canonical_unit": self.canonical_unit,
            "source_engine": self.source_engine,
            "report_type": self.report_type,
            "generated_at": self.generated_at,
            "source_data_freshness": self.source_data_freshness,
            "snapshot_ref": self.snapshot_ref,
            "source_ref": self.source_ref,
            "calculation_version": self.calculation_version,
            "ruleset_version": self.ruleset_version,
            "validation_warnings": list(self.validation_warnings),
            "incomplete_data_warnings": list(self.incomplete_data_warnings),
            "notice": self.notice,
        }


def build_provenance(
    *,
    company_id: int,
    company_name: str | None,
    period_label: str,
    report_type: str,
    period_from: str | None = None,
    period_to: str | None = None,
    source_engine: str = "Tryton",
    source_data_freshness: str = "live",
    snapshot_ref: str | None = None,
    source_ref: str | None = None,
    calculation_version: str = "1.0",
    ruleset_version: str | None = None,
    validation_warnings: list[str] | None = None,
    incomplete_data_warnings: list[str] | None = None,
    generated_at: datetime | None = None,
) -> Provenance:
    """Build a §13.7 provenance block.

    ``generated_at`` defaults to now (UTC). Callers SHOULD pass the
    report's own generation timestamp when the underlying service
    provides one, so MCP and REST results for the same snapshot agree.
    """
    stamp = generated_at or datetime.now(UTC)
    return Provenance(
        company_id=company_id,
        company_name=company_name,
        period_label=period_label,
        period_from=period_from,
        period_to=period_to,
        report_type=report_type,
        source_engine=source_engine,
        generated_at=stamp.isoformat(),
        source_data_freshness=source_data_freshness,
        snapshot_ref=snapshot_ref,
        source_ref=source_ref,
        calculation_version=calculation_version,
        ruleset_version=ruleset_version,
        validation_warnings=tuple(validation_warnings or ()),
        incomplete_data_warnings=tuple(incomplete_data_warnings or ()),
    )


# Re-exported for tests that assert the field set stays complete.
PROVENANCE_FIELDS: frozenset[str] = frozenset(
    Provenance(
        company_id=0,
        company_name=None,
        period_label="",
    ).to_dict()
)
