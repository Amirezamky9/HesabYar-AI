def test_reader_pdf_text_fallback_splits_columns() -> None:
    # A hand-built minimal PDF with one text line per row; pdfplumber
    # finds no table, so the reader falls back to text lines. The
    # hand-built font mangles the Persian words, so this test only
    # asserts the row structure — column splitting is covered by the
    # monkeypatched test below.
    pdf = _minimal_pdf(
        [
            "1405/08/26  واریز مشتری  1000000",
            "1405/08/26  پرداخت تأمین‌کننده  -250000",
        ]
    )
    detected = StatementFileReader().read_file(pdf, "statement.pdf")
    assert detected.file_format == StatementFileFormat.PDF
    assert len(detected.grid) == 2
    assert "1405/08/26" in " ".join(cell or "" for cell in detected.grid[0])
    assert "1000000" in " ".join(cell or "" for cell in detected.grid[0])
    assert any("text lines" in note for note in detected.detection_notes)


def test_reader_pdf_text_fallback_tab_split(monkeypatch: pytest.MonkeyPatch) -> None:
    # No tables: extract_text returns tab-separated lines, split into columns.
    import pdfplumber

    class FakePage:
        def extract_table(self):
            return None

        def extract_text(self):
            return "1405/08/26\tواریز مشتری\t1000000\n1405/08/26\tبرداشت\t-250000"

    class FakePdf:
        pages = [FakePage()]

        def __enter__(self):
            return self

        def __exit__(self, *args):
            return False

    monkeypatch.setattr(pdfplumber, "open", lambda stream: FakePdf())
    detected = StatementFileReader().read_file(b"%PDF-1.4 fake", "statement.pdf")
    assert detected.grid == [
        ["1405/08/26", "واریز مشتری", "1000000"],
        ["1405/08/26", "برداشت", "-250000"],
    ]


def test_reader_pdf_table_path(monkeypatch: pytest.MonkeyPatch) -> None:
    # Monkeypatch pdfplumber: two pages, each with a table; the second
    # page repeats the header row, which is dropped.
    import pdfplumber

    class FakePage:
        def __init__(self, table):
            self._table = table

        def extract_table(self):
            return self._table

        def extract_text(self):
            return None

    class FakePdf:
        pages = [
            FakePage(
                [
                    ["تاریخ", "شرح", "مبلغ"],
                    ["1405/08/26", "واریز", "1000000"],
                ]
            ),
            FakePage(
                [
                    ["تاریخ", "شرح", "مبلغ"],  # repeated header on the next page
                    ["1405/08/26", "برداشت", "-250000"],
                ]
            ),
        ]

        def __enter__(self):
            return self

        def __exit__(self, *args):
            return False

    monkeypatch.setattr(pdfplumber, "open", lambda stream: FakePdf())
    detected = StatementFileReader().read_file(b"%PDF-1.4 fake", "statement.pdf")
    assert detected.file_format == StatementFileFormat.PDF
    assert detected.grid[0] == ["تاریخ", "شرح", "مبلغ"]
    assert len(detected.grid) == 3  # repeated header dropped


def _minimal_pdf(lines: list[str]) -> bytes:
    """A hand-built one-page PDF with the given text lines (Latin-1 safe chars only)."""
    # Persian text is not Latin-1; the fallback test uses digit/ASCII
    # lines plus the Persian words encoded as UTF-16BE hex strings is
    # overkill — instead the test lines above are ASCII-safe except
    # the Persian words, so we build the content stream with escaped
    # octal bytes for the UTF-8 text. pdfplumber extracts the raw
    # bytes; the reader only needs the date + amount columns.
    text_ops = "".join(
        f"BT /F1 12 Tf 72 {700 - i * 20} Td ({_pdf_escape(line)}) Tj ET\n"
        for i, line in enumerate(lines)
    )
    stream = text_ops.encode("latin-1", errors="ignore")
    objects = [
        b"<< /Type /Catalog /Pages 2 0 R >>",
        b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] "
        b"/Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>",
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
        b"<< /Length %d >>\nstream\n" % len(stream) + stream + b"\nendstream",
    ]
    out = bytearray(b"%PDF-1.4\n")
    offsets = []
    for index, body in enumerate(objects, start=1):
        offsets.append(len(out))
        out += f"{index} 0 obj\n".encode() + body + b"\nendobj\n"
    xref_at = len(out)
    out += f"xref\n0 {len(objects) + 1}\n0000000000 65535 f \n".encode()
    for offset in offsets:
        out += f"{offset:010d} 00000 n \n".encode()
    out += (
        f"trailer\n<< /Size {len(objects) + 1} /Root 1 0 R >>\n"
        f"startxref\n{xref_at}\n%%EOF\n"
    ).encode()
    return bytes(out)


def _pdf_escape(line: str) -> str:
    return (
        line.replace("\\", "\\\\")
        .replace("(", "\\(")
        .replace(")", "\\)")
        .encode("utf-8", errors="ignore")
        .decode("latin-1", errors="ignore")
    )
