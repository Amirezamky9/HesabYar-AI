def _mapping(**overrides) -> BankColumnMapping:
    base = {
        "id": "m1",
        "tenant_id": "t1",
        "bank_key": "melli",
        "name": "Baam",
        "file_format": StatementFileFormat.CSV,
        "columns": {
            "date": "تاریخ",
            "description": "شرح",
            "debit": "برداشت",
            "credit": "واریز",
            "balance": "مانده",
            "bank_ref": "شماره سند",
        },
        "date_kind": "jalali",
        "currency_unit": FileCurrencyUnit.RIAL,
        "header_row": 0,
    }
    base.update(overrides)
    return BankColumnMapping(**base)


# -- normalisation ---------------------------------------------------------------


def test_normalize_digits_converts_persian_and_arabic_digits() -> None:
    assert normalize_digits("۱۲۳۴۵۶۷۸۹۰") == "1234567890"
    assert normalize_digits("١٢٣") == "123"
    assert normalize_digits("a1ب2") == "a1ب2"


def test_normalize_persian_text_unifies_arabic_letters() -> None:
    assert normalize_persian_text("علي كريم") == "علی کریم"
    # ZWNJ is preserved (it is meaningful Persian punctuation).
    assert normalize_persian_text("می‌شود") == "می‌شود"


# -- dates -------------------------------------------------------------------------


def test_parse_jalali_date_converts_to_gregorian() -> None:
    parsed = parse_jalali_date("1405/08/26")
    assert parsed.gregorian_date == datetime.date(2026, 11, 17)


def test_parse_jalali_date_accepts_persian_digits_and_dashes() -> None:
    assert parse_jalali_date("۱۴۰۵-۰۸-۰۱").gregorian_date == datetime.date(2026, 10, 23)


def test_parse_jalali_date_rejects_invalid_dates() -> None:
    with pytest.raises(ValueError, match="invalid Jalali date"):
        parse_jalali_date("1405/13/01")
    with pytest.raises(ValueError, match="not a Jalali date"):
        parse_jalali_date("not a date")


def test_parse_gregorian_date_accepts_iso() -> None:
    assert parse_gregorian_date("2026-11-17").gregorian_date == datetime.date(2026, 11, 17)


def test_parse_statement_date_dispatches_on_kind() -> None:
    assert parse_statement_date("1405/08/26", "jalali").gregorian_date == datetime.date(
        2026, 11, 17
    )
    assert parse_statement_date("2026-11-17", "gregorian").gregorian_date == datetime.date(
        2026, 11, 17
    )
    with pytest.raises(ValueError, match="unknown date_kind"):
        parse_statement_date("2026-11-17", "hijri")


# -- amounts -----------------------------------------------------------------------


@pytest.mark.parametrize(
    ("text", "expected"),
    [
        ("1,000,000", 1_000_000),
        ("۱٬۰۰۰٬۰۰۰", 1_000_000),
        ("1 000 000", 1_000_000),
        ("-250000", -250_000),
        ("250000-", -250_000),
        ("(250000)", -250_000),
        ("۰", 0),
    ],
)
def test_parse_amount_rial(text: str, expected: int) -> None:
    amount, rounded = parse_amount(text, FileCurrencyUnit.RIAL)
    assert amount == expected
    assert rounded is False


def test_parse_amount_toman_converts_times_ten() -> None:
    amount, rounded = parse_amount("175", FileCurrencyUnit.TOMAN)
    assert amount == 1750
    assert rounded is False


def test_parse_amount_toman_fraction_rounds_half_up() -> None:
    # 123.5 Toman = 1235 Rial exactly; 123.45 Toman = 1234.5 Rial → 1235 (HALF_UP).
    amount, rounded = parse_amount("123.45", FileCurrencyUnit.TOMAN)
    assert amount == 1235
    assert rounded is True


def test_parse_amount_rial_fraction_is_rejected() -> None:
    with pytest.raises(ValueError, match="fractional Rial"):
        parse_amount("123.5", FileCurrencyUnit.RIAL)


def test_parse_amount_rejects_empty_and_garbage() -> None:
    with pytest.raises(ValueError, match="empty amount"):
        parse_amount("   ", FileCurrencyUnit.RIAL)
    with pytest.raises(ValueError, match="not a number"):
        parse_amount("abc", FileCurrencyUnit.RIAL)


# -- match key ----------------------------------------------------------------------


def test_build_match_key_is_deterministic_and_normalised() -> None:
    date = FiscalDate(datetime.date(2026, 11, 17))
    key_a = build_match_key(date, 1_000_000, "واریز علي")
    key_b = build_match_key(date, 1_000_000, "واریز علی")
    assert key_a == key_b  # Arabic ي normalised before hashing
    assert build_match_key(date, 1_000_001, "واریز علی") != key_a
    assert build_match_key(FiscalDate(datetime.date(2026, 11, 18)), 1_000_000, "واریز علی") != key_a


# -- mapping suggestion + validation ---------------------------------------------------


def test_suggest_mapping_finds_persian_headers() -> None:
    suggested = suggest_mapping(["تاریخ", "شرح تراکنش", "واریز", "برداشت", "مانده"])
    assert suggested["date"] == "تاریخ"
    assert suggested["description"] == "شرح تراکنش"  # longest synonym wins
    assert suggested["credit"] == "واریز"
    assert suggested["debit"] == "برداشت"
    assert suggested["balance"] == "مانده"


def test_suggest_mapping_finds_english_headers() -> None:
    suggested = suggest_mapping(["Date", "Description", "Amount", "Balance"])
    assert suggested == {
        "date": "Date",
        "description": "Description",
        "amount": "Amount",
        "balance": "Balance",
    }


def test_validate_mapping_columns_requires_date_description_and_amount() -> None:
    assert validate_mapping_columns({"date": "تاریخ", "description": "شرح", "amount": "مبلغ"}) == []
    problems = validate_mapping_columns({"date": "تاریخ"})
    assert any("description" in p for p in problems)
    assert any("amount" in p for p in problems)
    problems = validate_mapping_columns(
        {"date": "تاریخ", "description": "شرح", "debit": "برداشت"}
    )
    assert any("credit" in p for p in problems)  # debit needs its credit pair
    problems = validate_mapping_columns(
        {"date": "تاریخ", "description": "شرح", "amount": "مبلغ", "bogus": "x"}
    )
    assert any("bogus" in p for p in problems)


# -- grid → rows -----------------------------------------------------------------------


def test_rows_from_grid_debit_credit_pair() -> None:
    grid: list[list[str | None]] = [
        ["تاریخ", "شرح", "برداشت", "واریز", "مانده", "شماره سند"],
        ["1405/08/26", "واریز مشتری", "", "۱٬۰۰۰٬۰۰۰", "۵٬۰۰۰٬۰۰۰", "REF-1"],
        ["1405/08/26", "پرداخت تأمین‌کننده", "۲۵۰٬۰۰۰", "", "۴٬۷۵۰٬۰۰۰", "REF-2"],
        ["", "", "", "", "", ""],  # empty rows are skipped
    ]
    rows = rows_from_grid(grid, _mapping(), FileCurrencyUnit.RIAL)
    assert len(rows) == 2
    assert rows[0].is_valid
    assert rows[0].amount_irr == 1_000_000
    assert rows[0].row_date is not None
    assert rows[0].row_date.gregorian_date == datetime.date(2026, 11, 17)
    assert rows[0].bank_ref == "REF-1"
    assert rows[0].balance_irr == 5_000_000
    assert rows[1].amount_irr == -250_000


def test_rows_from_grid_signed_amount_column() -> None:
    mapping = _mapping(
        columns={"date": "تاریخ", "description": "شرح", "amount": "مبلغ"},
        file_format=StatementFileFormat.XLSX,
    )
    grid: list[list[str | None]] = [
        ["تاریخ", "شرح", "مبلغ"],
        ["1405/08/26", "واریز", "1000000"],
        ["1405/08/26", "برداشت", "-250000"],
    ]
    rows = rows_from_grid(grid, mapping, FileCurrencyUnit.RIAL)
    assert [row.amount_irr for row in rows] == [1_000_000, -250_000]


def test_rows_from_grid_positional_columns() -> None:
    mapping = _mapping(
        columns={"date": "#0", "description": "#1", "amount": "#2"},
    )
    grid: list[list[str | None]] = [["x", "y", "z"], ["1405/08/26", "واریز", "1000000"]]
    rows = rows_from_grid(grid, mapping, FileCurrencyUnit.RIAL)
    assert len(rows) == 1
    assert rows[0].is_valid


def test_rows_from_grid_invalid_rows_keep_errors() -> None:
    grid: list[list[str | None]] = [
        ["تاریخ", "شرح", "برداشت", "واریز", "مانده", "شماره سند"],
        ["not-a-date", "واریز", "", "1000000", "", ""],
        ["1405/08/26", "واریز", "", "abc", "", ""],
        ["1405/08/26", "واریز", "100", "200", "", ""],  # both debit and credit
    ]
    rows = rows_from_grid(grid, _mapping(), FileCurrencyUnit.RIAL)
    assert len(rows) == 3
    assert all(not row.is_valid for row in rows)
    assert rows[0].errors  # bad date
    assert rows[1].errors  # bad amount
    assert rows[2].errors  # debit + credit both set


def test_rows_from_grid_enforces_row_cap() -> None:
    grid: list[list[str | None]] = [["تاریخ", "شرح", "مبلغ"]]
    grid.extend(
        [["1405/08/26", f"ردیف {i}", "1000"] for i in range(5)]
    )
    mapping = _mapping(columns={"date": "تاریخ", "description": "شرح", "amount": "مبلغ"})
    with pytest.raises(BankImportTooManyRowsError) as exc_info:
        rows_from_grid(grid, mapping, FileCurrencyUnit.RIAL, max_rows=4)
    assert exc_info.value.code == "BANK_IMPORT_TOO_MANY_ROWS"
    assert exc_info.value.details["rows"] == 5


def test_rows_from_grid_header_row_past_end() -> None:
    with pytest.raises(BankImportFileError):
        rows_from_grid([["a"]], _mapping(header_row=3), FileCurrencyUnit.RIAL)


def test_rows_from_grid_toman_unit_converts() -> None:
    mapping = _mapping(columns={"date": "تاریخ", "description": "شرح", "amount": "مبلغ"})
    grid: list[list[str | None]] = [["تاریخ", "شرح", "مبلغ"], ["1405/08/26", "واریز", "۱۷۵"]]
    rows = rows_from_grid(grid, mapping, FileCurrencyUnit.TOMAN)
